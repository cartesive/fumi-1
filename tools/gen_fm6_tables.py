"""The FM6 core's start-up tables (firmware/src/dsp/fm6_tables.h): msfa built them with double math at
start-up; the firmware has no double, so they are precomputed here. 44.1 kHz, 32-sample blocks.

  tools/gen_fm6_tables.py firmware/src/dsp/fm6_tables.h
"""
