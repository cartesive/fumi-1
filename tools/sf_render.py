"""Render every FuMi-1 instrument key by key through the host simulator, for the SoundFont (tools/sf_bank.py).
  python3 tools/sf_render.py [RENDER_DIR] [--only N] [--gain G] [--host build/host/fumi_host]
One scenario per instrument: the reverb turned to 0, PRESETS stepped to the instrument (checked), then each of
the sixteen white keys held (6 s plucked, 4.5 s sustained, 3 s percussion), released and left to die, each into
its own WAV: RENDER_DIR/NN-Name/kNN.wav. Everything else at the boot defaults: 1本, SUIKO, 余韻 80, level 80,
MASTER full. The recording gain (wavgain, default 8 = +18 dB: FuMi's output is -21 dB by design) is halved
and the instrument rendered again if any sample clipped. A note still sounding when the next key is recorded
is reported (the lead-in of a file should be silent)."""
import argparse, subprocess, sys, wave
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sf_bank  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
P_VOICE, P_REVERB = 7, 26                        # fumi.h's parameter enum, as `expect parN` counts them
TAIL_MS = 3000                                   # after the key is released: the 余韻 (80) has died by then

def scenario(program, kind):
    L = ["# generated by tools/sf_render.py: one instrument, every white key into its own WAV", "wait 400",
         "turn K4 -70 40", f"expect par{P_REVERB} 0", "master 4096"]
    if program:
        L += [f"turn PRESET {program} 250", "wait 900"]
    L += [f"expect par{P_VOICE} {program}", "shot home.png"]
    hold = sf_bank.HOLD_MS[kind]
    for k in range(sf_bank.NKEY):
        L += [f"wav k{k:02d}.wav", "wait 30", f"key w{k} down", f"wait {hold}", f"key w{k} up", f"wait {TAIL_MS}",
              "wavstop", "wait 200"]
    return "\n".join(L) + "\n"

def peaks(d):
    """(peak, lead-in peak) in 16-bit units for each WAV of an instrument folder"""
    out = []
    for k in range(sf_bank.NKEY):
        with wave.open(str(d / f"k{k:02d}.wav")) as w:
            x = np.abs(np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(int))
        out.append((int(x.max()), int(x[:2 * int(0.02 * sf_bank.SR)].max())))
    return out

def render_one(host, render_dir, program, name, kind, gain, log=print):
    d = Path(render_dir) / f"{program:02d}-{name}"
    d.mkdir(parents=True, exist_ok=True)
    while True:
        sc = d / "render.fumi"
        sc.write_text(scenario(program, kind).replace("master 4096", f"master 4096\nwavgain {gain:g}"))
        r = subprocess.run([str(host), str(sc), str(d)], capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f"{name}: the host failed:\n{r.stdout}{r.stderr}")
        pk = peaks(d)
        top = max(p for p, _ in pk)
        if top >= 32767 and gain > 0.5:
            log(f"  {program:03d} {name:<10} clipped at gain {gain:g}: again at {gain / 2:g}")
            gain /= 2
            continue
        bleed = max(l for _, l in pk)
        log(f"  {program:03d} {name:<10} {kind:<7} gain {gain:g}  peak {20 * np.log10(top / 32767):5.1f} dBFS"
            + (f"  LEAD-IN NOT SILENT ({20 * np.log10(bleed / 32767):.0f} dBFS: the last note still sounding)" if bleed > 32767 * 10 ** (-60 / 20) else ""))
        return gain

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("render_dir", nargs="?", default=str(ROOT / "build/sf/render"))
    ap.add_argument("--only", type=int, help="one instrument (program number)")
    ap.add_argument("--gain", type=float, default=8.0)
    ap.add_argument("--host", default=str(ROOT / "build/host/fumi_host"))
    a = ap.parse_args(argv)
    for p, (name, kind) in enumerate(sf_bank.names()):
        if a.only is None or a.only == p:
            render_one(a.host, a.render_dir, p, name, kind, a.gain)

if __name__ == "__main__":
    main()
